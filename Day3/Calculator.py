# Calculator
num1=float(input("enter your first number "))
oper=input("choose an operation ")
num2=float(input("enter your first number "))
if oper=="+":
    print(num1+num2)
elif oper=="-":
    print(num1-num2)
elif oper=="*":
    print(num1*num2)
elif oper=="/":
    print(num1/num2)
elif oper=="%":
    print(num1%num2)
else:
    print("sorry")













